export function themeColors(id: PaletteId, dark: boolean) {
  const [bg, card, text, muted, border, primary, button, soft, secondary, highlight] =
    values[paletteId(id)][dark ? 1 : 0];
  return {
    bg,
    card,
    text,
    muted,
    border,
    primary,
    button,
    soft,
    secondary,
    highlight,
    danger: dark ? "#FF9A9A" : "#B52C43",
  };
}
